import numpy as np
# спрашиваем число строк
n = int(input("Введи N: "))
# спрашиваем число столбцов
m = int(input("Введи M: "))
# создаем пустую матрицу
a = np.zeros((n, m))
# заполняем матрицу числами с клавиатуры
print("Вводи числа для матрицы:")
# идем по строкам
for i in range(n):
    # идем по столбцам
    for j in range(m):
        print("Введи число для строки", i, "столбца", j)
        num = int(input())
        a[i,j] = num
# выводим название
print("\nПервая матрица:")
# выводим матрицу
print(a)
# создаем пустую матрицу для транспонированной
b = np.zeros((m, n))
# идем по строкам
for i in range(n):
    # идем по столбцам
    for j in range(m):
        # меняем местами строки и столбцы
        b[j,i] = a[i,j]
# выводим название
print("\nВторая матрица (транспонированная):")
# выводим матрицу
print(b)
# считаем определители по формуле для 2 на 2
if n == 2 and m == 2:
    # формула a*d - b*c для первой
    d = a[0,0] * a[1,1] - a[0,1] * a[1,0]
    # формула a*d - b*c для второй
    e = b[0,0] * b[1,1] - b[0,1] * b[1,0]
    # выводим первый определитель
    print("\nОпределитель первой:", d)
    # выводим второй определитель
    print("Определитель второй:", e)
    # сравниваем их
    if d == e:
        # если равны
        print("Определители равны!")
    else:
        # если не равны
        print("Определители не равны!")
else:
    # если матрица не 2 на 2
    print("\nДля этой формулы введи N = 2 и M = 2")