import pandas as pd  # подключаем библиотеку
# создаем пустую таблицу
d = pd.DataFrame({'ФИО': [], 'Адрес': [], 'Телефон': [], 'Дата рождения': []})
# выводим название
print("Адресная книга")
# бесконечный цикл
while True:
    # показываем меню
    print("\n1 - посмотреть всех")
    print("2 - добавить человека")
    print("3 - удалить человека")
    print("4 - изменить запись")
    print("0 - выйти")
    # спрашиваем выбор
    v = input("Что выбираешь? ")
    # если 1
    if v == '1':
        print("\nВсе записи:")
        # выводим таблицу
        print(d)
    # если 2
    elif v == '2':
        print("\nДобавляем нового человека:")
        # спрашиваем ФИО
        a = input("Введи ФИО: ")
        # спрашиваем адрес
        b = input("Введи адрес: ")
        # спрашиваем телефон
        c = input("Введи телефон: ")
        # спрашиваем дату рождения
        e = input("Введи дату рождения: ")
        # добавляем строку
        d.loc[len(d)] = [a, b, c, e]
        # пишем что добавили
        print("Добавил!")
    # если 3
    elif v == '3':
        print("\nКого удаляем?")
        # показываем таблицу
        print(d)
        # спрашиваем номер строки
        x = int(input("Введи номер строки: "))
        # удаляем строку
        d = d[d.index != x]
        # пишем что удалили
        print("Удалил!")
    # если 4
    elif v == '4':
        print("\nКого меняем?")
        # показываем таблицу
        print(d)
        # спрашиваем номер строки
        x = int(input("Введи номер строки: "))
        # просим новые данные
        print("Введи новые данные:")
        # новое ФИО
        a = input("ФИО: ")
        # новый адрес
        b = input("Адрес: ")
        # новый телефон
        c = input("Телефон: ")
        # новая дата рождения
        e = input("Дата рождения: ")
        # меняем строку
        d.loc[x] = [a, b, c, e]
        # пишем что изменили
        print("Изменил!")
    # если 0
    elif v == '0':
        # прощаемся
        print("Пока!")
        # выходим из цикла
        break